    'surface', left(nullif(p_metadata ->> 'surface', ''), 40),
    'mode', left(nullif(p_metadata ->> 'mode', ''), 10),
    'source', left(nullif(p_metadata ->> 'source', ''), 40)
  ));

  insert into public.product_events (session_id, event_name, entity_type, entity_id, metadata)
  values (p_session_id, p_event_name, p_entity_type, p_entity_id, v_metadata);
end;
$$;

create or replace function public.admin_list_review_reports(p_limit integer default 50)
returns table (
  report_id uuid,
  review_id uuid,
  movie_title text,
  author_display_name text,
  reporter_display_name text,
  reason text,
  detail text,
  status text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.admin_access
    where user_id = auth.uid() and can_moderate_reviews
  ) then raise exception 'admin_moderate_reviews_required'; end if;

  return query
  select reports.id,
         reports.review_id,
         movies.title,
         coalesce(nullif(trim(authors.display_name), ''), 'FLICK 사용자'),
         coalesce(nullif(trim(reporters.display_name), ''), 'FLICK 사용자'),
         reports.reason,
         reports.detail,
         reports.status,
         reports.created_at
  from public.review_reports reports
  join public.reviews reviews on reviews.id = reports.review_id
  join public.movies movies on movies.id = reviews.movie_id
  left join public.profiles authors on authors.id = reviews.user_id
  left join public.profiles reporters on reporters.id = reports.reporter_user_id
  where reports.status = 'open'
  order by reports.created_at asc
  limit least(greatest(coalesce(p_limit, 50), 1), 100);
end;
$$;

create or replace function public.admin_resolve_review_report(p_report_id uuid, p_action text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_review_id uuid;
begin
  if not exists (
    select 1 from public.admin_access
    where user_id = auth.uid() and can_moderate_reviews
  ) then raise exception 'admin_moderate_reviews_required'; end if;
  if p_action not in ('dismiss', 'make_private') then raise exception 'invalid_report_action'; end if;

  select review_id into v_review_id from public.review_reports where id = p_report_id and status = 'open' for update;
  if v_review_id is null then raise exception 'report_not_found'; end if;

  if p_action = 'make_private' then
    update public.reviews set visibility = 'private', updated_at = now() where id = v_review_id;
  end if;

  update public.review_reports
  set status = case when p_action = 'make_private' then 'actioned' else 'dismissed' end,
      resolved_by = auth.uid(), resolved_at = now(), updated_at = now()
  where id = p_report_id;

  insert into public.admin_audit_events (admin_user_id, action, target_type, target_id, metadata)
  values (
    auth.uid(),
    case when p_action = 'make_private' then 'review_report_made_private' else 'review_report_dismissed' end,
    'review_report',
    p_report_id::text,
    jsonb_build_object('review_id', v_review_id)
  );
end;
$$;

