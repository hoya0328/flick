create or replace function public.add_review_comment(p_review_id uuid, p_body text, p_parent_id uuid default null)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_comment_id uuid;
  v_parent_review_id uuid;
  v_parent_parent_id uuid;
begin
  if auth.uid() is null then raise exception 'authentication_required'; end if;
  if not public.is_public_completed_review(p_review_id) then raise exception 'review_not_found'; end if;
  if char_length(trim(coalesce(p_body, ''))) not between 1 and 500 then raise exception 'invalid_comment'; end if;

  if p_parent_id is not null then
    select review_id, parent_id into v_parent_review_id, v_parent_parent_id
    from public.review_comments where id = p_parent_id and status = 'visible';
    if v_parent_review_id is distinct from p_review_id then raise exception 'invalid_parent_comment'; end if;
    if v_parent_parent_id is not null then raise exception 'reply_depth_exceeded'; end if;
  end if;

  insert into public.review_comments (review_id, user_id, parent_id, body)
  values (p_review_id, auth.uid(), p_parent_id, trim(p_body))
  returning id into v_comment_id;
  return v_comment_id;
end;
$$;

create or replace function public.remove_review_comment(p_comment_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'authentication_required'; end if;
  update public.review_comments
  set body = '', status = 'removed', updated_at = now()
  where id = p_comment_id and user_id = auth.uid() and status = 'visible';
  if not found then raise exception 'comment_not_found'; end if;
end;
$$;

create or replace function public.report_review(p_review_id uuid, p_reason text, p_detail text default '')
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'authentication_required'; end if;
  if p_reason not in ('spoiler', 'harassment', 'personal_info', 'copyright', 'other') then raise exception 'invalid_report_reason'; end if;
  if not public.is_public_completed_review(p_review_id) then raise exception 'review_not_found'; end if;
  if exists (select 1 from public.reviews where id = p_review_id and user_id = auth.uid()) then raise exception 'cannot_report_own_review'; end if;

  insert into public.review_reports (review_id, reporter_user_id, reason, detail)
  values (p_review_id, auth.uid(), p_reason, left(trim(coalesce(p_detail, '')), 500))
  on conflict (review_id, reporter_user_id) do update
  set reason = excluded.reason, detail = excluded.detail, status = 'open', resolved_by = null, resolved_at = null, updated_at = now();
end;
$$;

create or replace function public.track_product_event(
  p_session_id uuid,
  p_event_name text,
  p_entity_type text,
  p_entity_id uuid default null,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_metadata jsonb;
begin
  if auth.uid() is null then raise exception 'authentication_required'; end if;
  if p_event_name not in ('public_review_view', 'movie_detail_open', 'review_like', 'review_save', 'comment_create', 'report_submit', 'record_start') then raise exception 'invalid_event_name'; end if;
  if p_entity_type not in ('review', 'movie', 'record') then raise exception 'invalid_entity_type'; end if;

