create or replace function public.list_public_reviews(
  p_mode text default null,
  p_cursor timestamptz default null,
  p_limit integer default 20
)
returns table (
  review_id uuid,
  author_display_name text,
  movie_id uuid,
  movie_title text,
  poster_path text,
  mode text,
  watched_at date,
  rating numeric,
  one_line text,
  body_excerpt text,
  spoiler boolean,
  updated_at timestamptz,
  like_count bigint,
  comment_count bigint,
  save_count bigint,
  viewer_liked boolean,
  viewer_saved boolean
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'authentication_required'; end if;
  if p_mode is not null and p_mode not in ('light', 'core') then raise exception 'invalid_mode'; end if;

  return query
  select reviews.id,
         coalesce(nullif(trim(profiles.display_name), ''), 'FLICK 사용자'),
         movies.id,
         movies.title,
         movies.poster_path,
         reviews.mode,
         reviews.watched_at,
         reviews.rating,
         reviews.one_line,
         case when reviews.spoiler then '' else left(reviews.body, 280) end,
         reviews.spoiler,
         reviews.updated_at,
         (select count(*) from public.review_likes likes where likes.review_id = reviews.id),
         (select count(*) from public.review_comments comments where comments.review_id = reviews.id and comments.status = 'visible'),
         (select count(*) from public.review_saves saves where saves.review_id = reviews.id),
         exists (select 1 from public.review_likes likes where likes.review_id = reviews.id and likes.user_id = auth.uid()),
         exists (select 1 from public.review_saves saves where saves.review_id = reviews.id and saves.user_id = auth.uid())
  from public.reviews reviews
  join public.movies movies on movies.id = reviews.movie_id
  left join public.profiles profiles on profiles.id = reviews.user_id
  where reviews.visibility = 'public'
    and reviews.status = 'completed'
    and (p_mode is null or reviews.mode = p_mode)
    and (p_cursor is null or reviews.updated_at < p_cursor)
  order by reviews.updated_at desc, reviews.id desc
  limit least(greatest(coalesce(p_limit, 20), 1), 50);
end;
$$;

